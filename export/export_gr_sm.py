#!/usr/bin/env python3
"""Generate the restricted repository "Dynamic Theory: GR and SM".

The restricted repo holds only what the manuscript relies on (export/gr-sm.manifest)
and is GENERATED from this repository. Never edit the generated copy: change the
source here, or the manifest, and re-run.

    python3 export/export_gr_sm.py [TARGET]          # default ~/lean/Dynamic-Theory-GR-SM
    python3 export/export_gr_sm.py TARGET --link-lake # also hard-link .lake/packages

A regenerate keeps TARGET/.git and TARGET/.lake and replaces everything else. A
non-empty TARGET without the marker file is refused, so nothing hand-made is lost.
"""
import os, re, shutil, subprocess, sys

SRC = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MANIFEST = os.path.join(SRC, "export", "gr-sm.manifest")
MARKER = ".generated-by-export"
KEEP = {".git", ".lake"}
ROOT_FILES = ["lean-toolchain", "lake-manifest.json", "Basic.lean", "PhyslibCompat.lean",
              "LICENSE", ".gitignore", "ASSUMPTIONS.md", "linter.py"]
RESULTS = {"Sage": "sage-results", "Lean": "lean-results", "Cadabra": "cadabra-results"}
TITLE = "Dynamic Theory: General Relativity and the Standard Model"
SI_SECTION = {"F": "S2", "G": "S3", "S": "S4", "P": "S5"}   # code index is Sec. S6
POINTER = "Supplementary_Material.pdf"                      # full-SI pointer, replaced


def die(msg):
    sys.exit("export_gr_sm: " + msg)


def read_manifest():
    """Sections [(heading, [path])], the flat path list, and {path: [tag]}."""
    sections, cur, tags = [], None, {}
    for raw in open(MANIFEST, encoding="utf-8"):
        line = raw.strip()
        if line.startswith("## "):
            cur = (line[3:], [])
            sections.append(cur)
        elif line and not line.startswith("#"):
            if cur is None:
                die("entry before first section: " + line)
            path, *rest = line.split()
            if path.endswith((".sage", ".lean", ".cdb")):
                if len(rest) != 1 or not re.fullmatch(r"[FGSP]\d+(,[FGSP]\d+)*", rest[0]):
                    die("script without a valid SI step tag: " + line)
                tags[path] = rest[0].split(",")
            elif rest:
                die("data file with a tag: " + line)
            cur[1].append(path)
    files = [f for _, fs in sections for f in fs]
    missing = [f for f in files if not os.path.isfile(os.path.join(SRC, f))]
    if missing:
        die("missing in source:\n  " + "\n  ".join(missing))
    if len(set(files)) != len(files):
        die("duplicate manifest entries")
    return sections, files, tags


def pointer(tags):
    secs = sorted({SI_SECTION[t[0]] for t in tags})
    return "Supplementary Materials: step%s %s, Sec. %s (code index: Sec. S6)." % (
        "s" if len(tags) > 1 else "", ", ".join("[%s]" % t for t in tags), ", ".join(secs))


def retag(tgt, rel, tags):
    """Point the header of an exported script at its step in the short SI.

    The source headers cite the full stand-alone SI ([Cn] tags); the restricted
    repo accompanies the short SI, so the pointer is rewritten in the copy only.
    """
    path = os.path.join(tgt, rel)
    lines = open(path, encoding="utf-8").read().split("\n")
    hits = [i for i, l in enumerate(lines) if POINTER in l]
    if len(hits) > 1:
        die("more than one SI pointer in " + rel)
    if hits:
        i = hits[0]
        lead = "# " if lines[i].lstrip().startswith("#") else "  "
        lines[i] = lead + pointer(tags)
        if i and "Full derivation, context and provenance" in lines[i - 1]:
            del lines[i - 1]
    elif rel.endswith(".sage"):
        rules = [i for i, l in enumerate(lines[:40]) if l.startswith("# ---")]
        if len(rules) < 2:
            die("no header block to tag in " + rel)
        lines.insert(rules[1], "# " + pointer(tags))
    else:
        die("no SI pointer to rewrite in " + rel)
    text = "\n".join(lines)
    # RUN lines in the source name the author's Sage binary and old numbered names.
    text = re.sub(r"# RUN: \S*/sage (?:\d+_)?(\S+)", r"# RUN: sage \1", text)
    write(tgt, rel, text)


def module(path):
    return path[:-len(".lean")].replace("/", ".")


def lean_closure(lean_files):
    """Every Layer* import of a kept module must itself be kept."""
    kept = {module(f) for f in lean_files}
    bad = []
    for f in lean_files:
        for m in re.findall(r"^import\s+(\S+)", open(os.path.join(SRC, f), encoding="utf-8").read(), re.M):
            if m.startswith("Layer") and m not in kept:
                bad.append("%s imports %s" % (f, m))
    if bad:
        die("Lean import closure broken:\n  " + "\n  ".join(bad))
    return sorted(kept)


def prepare_target(tgt):
    if os.path.isdir(tgt) and os.listdir(tgt):
        if not os.path.exists(os.path.join(tgt, MARKER)):
            die("%s is non-empty and was not generated by this script; refusing." % tgt)
        for name in os.listdir(tgt):
            if name in KEEP:
                continue
            p = os.path.join(tgt, name)
            shutil.rmtree(p) if os.path.isdir(p) and not os.path.islink(p) else os.remove(p)
    os.makedirs(tgt, exist_ok=True)


def copy(rel, tgt):
    dst = os.path.join(tgt, rel)
    os.makedirs(os.path.dirname(dst), exist_ok=True)
    shutil.copy2(os.path.join(SRC, rel), dst)


def companions(rel):
    """Result files that travel with a script."""
    layer, kind, name = rel.split("/")
    if kind not in RESULTS or not name.endswith((".sage", ".lean", ".cdb")):
        return []                      # data files travel alone
    stem = os.path.splitext(name)[0]
    out = "%s/%s/%s.out.txt" % (layer, RESULTS[kind], stem)
    if os.path.isfile(os.path.join(SRC, out)):
        return [out]
    if kind == "Lean":
        return []                      # not every Lean module has a stored log
    die("no stored output for " + rel)


def write(tgt, rel, text):
    with open(os.path.join(tgt, rel), "w", encoding="utf-8") as fh:
        fh.write(text)


def gen_lean(tgt, mods):
    imports = "".join("import %s\n" % m for m in mods)
    write(tgt, "DynamicTheory.lean",
          "-- Root aggregator (generated by export/export_gr_sm.py).\n\nimport Basic\n" + imports)
    ax = open(os.path.join(SRC, "AxiomCheck.lean"), encoding="utf-8").read()
    ax, n = re.subn(r"(?:^import .*\n)+", "import Basic\n" + imports, ax, count=1, flags=re.M)
    if n != 1:
        die("could not rewrite the AxiomCheck import block")
    write(tgt, "AxiomCheck.lean", ax)
    lake = open(os.path.join(SRC, "lakefile.lean"), encoding="utf-8").read()
    globs = ",\n".join(["    .one `DynamicTheory", "    .one `Basic", "    .one `PhyslibCompat"]
                       + ["    .one `%s" % m for m in mods])
    lake, n = re.subn(r"globs := #\[.*?\n  \]", "globs := #[\n%s\n  ]" % globs, lake, flags=re.S)
    if n != 1:
        die("could not rewrite the lakefile globs")
    lake = re.sub(r"\n  -- Root aggregator.*?\n(?=  globs)", "\n  -- Explicit module list (generated by export/export_gr_sm.py).\n",
                  lake, flags=re.S)
    write(tgt, "lakefile.lean", lake)


def gen_readme(tgt, sections, files):
    L = ["# " + TITLE, "",
         "Code accompanying the manuscript *Dynamic Theory: recovery of General Relativity",
         "and the Standard Model from conservation of mass*. It contains only the derivations",
         "and checks that the manuscript relies on.", "",
         "## Tools", "",
         "- **SageMath** (`Layer*/Sage/*.sage`): assertion-driven derivations; every check",
         "  prints PASS or the script stops. Stored output in `Layer*/sage-results/`.",
         ] + ([
         "- **Cadabra2** (`Layer*/Cadabra/*.cdb`): independent tensor-algebra cross-checks;",
         "  output in `Layer*/cadabra-results/`.",
         ] if any(f.endswith(".cdb") for f in files) else []) + [
         "- **Lean 4 + Mathlib + PhysLib** (`Layer*/Lean/*.lean`): machine-checked theorems.",
         "  `AxiomCheck.lean` reports the axiom footprint of every `DTWilliams` declaration.", "",
         "## Running", "",
         "```",
         "lake build                          # Lean (toolchain pinned in lean-toolchain)",
         "lake env lean AxiomCheck.lean       # axiom footprint: 0 sorry, standard axioms only",
         "cd Layer3 && sage Sage/<name>.sage > sage-results/<name>.out.txt",
         "python3 linter.py                   # consistency sweep over all stored outputs",
         "```", "",
         "Assumptions beyond the three laws are tabulated in `ASSUMPTIONS.md`.", "",
         "## Contents"]
    for head, files in sections:
        L += ["", "### " + head, ""]
        L += ["- `%s`" % f for f in files]
    L += ["", "## Licence", "", "See `LICENSE`.", ""]
    write(tgt, "README.md", "\n".join(L))


def link_lake(tgt):
    src_pk = os.path.join(SRC, ".lake", "packages")
    dst_pk = os.path.join(tgt, ".lake", "packages")
    if os.path.exists(dst_pk):
        return
    os.makedirs(os.path.dirname(dst_pk), exist_ok=True)
    subprocess.run(["cp", "-al", src_pk, dst_pk], check=True)


def main():
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    tgt = os.path.abspath(os.path.expanduser(args[0] if args else "~/lean/Dynamic-Theory-GR-SM"))
    if os.path.commonpath([tgt, SRC]) == SRC:
        die("target must lie outside the source repository")
    sections, files, tags = read_manifest()
    mods = lean_closure([f for f in files if f.endswith(".lean")])
    prepare_target(tgt)
    for f in files:
        for g in [f] + companions(f):
            copy(g, tgt)
    for f, t in tags.items():
        retag(tgt, f, t)
    for f in ROOT_FILES:
        copy(f, tgt)
    gen_lean(tgt, mods)
    gen_readme(tgt, sections, files)
    head = subprocess.run(["git", "-C", SRC, "rev-parse", "--short", "HEAD"],
                          capture_output=True, text=True).stdout.strip()
    write(tgt, MARKER, "Generated by export/export_gr_sm.py from Dynamic-Theory @ %s.\n"
          "Do not edit: change the source repository and regenerate.\n" % head)
    if "--link-lake" in sys.argv:
        link_lake(tgt)
    # linter.out.txt is part of the published record; regenerate it on every export.
    subprocess.run(["python3", "linter.py"], cwd=tgt, check=True, stdout=subprocess.DEVNULL)
    if "RESULT: CLEAN" not in open(os.path.join(tgt, "linter.out.txt"), encoding="utf-8").read():
        die("linter not CLEAN in the exported copy; see linter.out.txt")
    n = {k: sum(f.endswith(k) for f in files) for k in (".sage", ".lean", ".cdb")}
    print("exported to %s: %d Sage, %d Lean, %d Cadabra (source @ %s)"
          % (tgt, n[".sage"], n[".lean"], n[".cdb"], head))


if __name__ == "__main__":
    main()
